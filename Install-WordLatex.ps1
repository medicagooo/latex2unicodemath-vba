#Requires -Version 7.0
[CmdletBinding()]
param()

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

if (-not $IsWindows) {
    throw 'Run this installer on Windows with desktop Microsoft Word installed.'
}

$sessionId = (Get-Process -Id $PID).SessionId
function Get-SessionWord {
    Get-Process -Name WINWORD -ErrorAction SilentlyContinue |
        Where-Object SessionId -eq $sessionId
}
$runningWord = Get-SessionWord
if ($runningWord -and -not ($runningWord | Where-Object MainWindowHandle -ne 0)) {
    Wait-Process -Id $runningWord.Id -Timeout 5 -ErrorAction SilentlyContinue
    $runningWord = Get-SessionWord
}
if ($runningWord) {
    throw 'Close Word completely, then run the installer again.'
}

try {
    $word = New-Object -ComObject Word.Application
} catch {
    throw "Could not start desktop Microsoft Word to read its Startup path. $($_.Exception.Message)"
}

try {
    $startup = $word.StartupPath
} finally {
    try {
        $word.Quit(0)
    } finally {
        [void][Runtime.InteropServices.Marshal]::FinalReleaseComObject($word)
    }
}

if ([string]::IsNullOrWhiteSpace($startup) -or -not [IO.Path]::IsPathFullyQualified($startup)) {
    throw 'Word did not report an absolute Startup path.'
}

